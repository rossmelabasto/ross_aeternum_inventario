-- Aeternum · Inventario y ventas
-- Tres tablas: categorias (1) ──< productos (N) ──< ventas (N)

create table public.categorias (
  id          bigint generated by default as identity primary key,
  nombre      text not null unique,
  descripcion text,
  created_at  timestamptz not null default now()
);

create table public.productos (
  id           bigint generated by default as identity primary key,
  categoria_id bigint not null references public.categorias (id) on delete restrict,
  nombre       text not null,
  marca        text not null,
  talla        numeric(3,1) not null check (talla between 30 and 50),
  condicion    text not null default 'Usado - buen estado'
               check (condicion in ('Nuevo', 'Usado - como nuevo', 'Usado - buen estado')),
  precio       numeric(10,2) not null check (precio > 0),
  stock        integer not null default 0 check (stock >= 0),
  image_url    text,
  created_at   timestamptz not null default now()
);

create table public.ventas (
  id              bigint generated by default as identity primary key,
  producto_id     bigint not null references public.productos (id) on delete restrict,
  cantidad        integer not null default 1 check (cantidad > 0),
  precio_unitario numeric(10,2) not null check (precio_unitario > 0),
  total           numeric(10,2) generated always as (cantidad * precio_unitario) stored,
  canal           text not null default 'Tienda'
                  check (canal in ('Tienda', 'Marketplace', 'WhatsApp', 'Instagram')),
  created_at      timestamptz not null default now()
);

create index productos_categoria_idx on public.productos (categoria_id);
create index ventas_producto_idx on public.ventas (producto_id);

-- Seguridad a nivel de filas: sin una política, nadie lee ni escribe por la API pública.
alter table public.categorias enable row level security;
alter table public.productos  enable row level security;
alter table public.ventas     enable row level security;

-- El catálogo (categorías y productos) es público solo para lectura.
create policy "Catalogo visible para todos" on public.categorias
  for select to anon, authenticated using (true);
create policy "Productos visibles para todos" on public.productos
  for select to anon, authenticated using (true);
-- Las ventas no tienen política pública: solo el backend las ve.
